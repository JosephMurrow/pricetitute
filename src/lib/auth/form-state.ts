/**
 * Состояние формы между отправками. Живёт отдельным модулем: из файла с
 * "use server" разрешено экспортировать только асинхронные функции.
 */
export interface FormState {
  /** Общая ошибка формы. */
  error?: string;
  /** Ошибки по конкретным полям. */
  fieldErrors?: Record<string, string>;
  /** Сообщение об успехе, если форма не уводит на другую страницу. */
  ok?: string;
  /**
   * Введённые значения, чтобы вернуть их в поля после неудачной отправки:
   * React 19 сбрасывает неконтролируемую форму на каждом вызове экшена.
   * Пароли сюда не кладём.
   */
  values?: Record<string, string>;
}

export const EMPTY_FORM_STATE: FormState = {};
